import tailwindcss from '@tailwindcss/vite';
import { defineConfig } from 'wxt';

/**
 * Hosts the background worker may call without an extra permission prompt.
 * Match patterns ignore ports, so these cover every local backend (Ollama
 * :11434, LM Studio :1234, llama.cpp :8080, vLLM :8000, ...).
 */
const LOCAL_HOSTS = ['http://localhost/*', 'http://127.0.0.1/*', 'http://[::1]/*'];

export default defineConfig({
  srcDir: 'src',
  modules: ['@wxt-dev/module-react'],
  // Explicit imports everywhere: easier to read, lint and grep than auto-imports.
  imports: false,
  vite: () => ({
    plugins: [tailwindcss()],
    build: {
      // Everything is bundled; nothing is fetched at runtime.
      assetsInlineLimit: 0,
    },
  }),
  manifest: ({ browser }) => {
    const isFirefox = browser === 'firefox';
    return {
      name: 'Tether',
      description:
        'Local-model browser copilot with computer use. Every token is generated on your machine.',
      permissions: [
        'storage',
        'activeTab',
        'scripting',
        'tabs',
        'contextMenus',
        'alarms',
        'commands',
        // Chromium-only APIs. Firefox uses sidebar_action (generated by WXT
        // from the sidepanel entrypoint) and has no offscreen documents.
        ...(isFirefox ? [] : ['sidePanel', 'offscreen']),
      ],
      optional_permissions: [...(isFirefox ? [] : ['debugger']), 'downloads'],
      host_permissions: LOCAL_HOSTS,
      optional_host_permissions: ['<all_urls>'],
      commands: isFirefox
        ? {
            _execute_sidebar_action: {
              suggested_key: { default: 'Ctrl+Shift+L', mac: 'Command+Shift+L' },
              description: 'Open Tether',
            },
          }
        : {
            _execute_action: {
              suggested_key: { default: 'Ctrl+Shift+L', mac: 'Command+Shift+L' },
              description: 'Open Tether',
            },
          },
      action: {
        default_title: 'Open Tether',
      },
      content_security_policy: {
        extension_pages: "script-src 'self'; object-src 'self';",
      },
      ...(isFirefox
        ? {
            browser_specific_settings: {
              gecko: {
                id: 'tether@local',
                strict_min_version: '128.0',
                // Tether sends nothing anywhere except the user's own endpoints.
                data_collection_permissions: { required: ['none'] },
              },
            },
          }
        : { minimum_chrome_version: '120' }),
    };
  },
  hooks: {
    // The runtime-registered content script declares `<all_urls>` matches,
    // which WXT copies into host_permissions. Tether injects it via activeTab
    // instead, and `<all_urls>` stays an optional, in-flow grant.
    'build:manifestGenerated': (_wxt, manifest) => {
      const mv3 = manifest as { host_permissions?: string[] };
      mv3.host_permissions = mv3.host_permissions?.filter((p) => p !== '<all_urls>');
    },
  },
  webExt: {
    // `pnpm dev` opens a browser with the extension loaded; keep it on a
    // dedicated profile so dev state never touches the user's real profile.
    chromiumArgs: ['--user-data-dir=./.wxt/chrome-data'],
  },
});
